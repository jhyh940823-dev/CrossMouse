import AppKit
import Foundation

/// One-way text only. Each encrypted frame stays below the existing 4096-byte
/// ceiling, including JSON escaping. No clipboard content appears in diagnostics.
public enum TextClipboardWire {
    public static let capability = "text-chunks-1"
    public static let maxBytes = 256 * 1024
    public static let chunkBytes = 2048

    public static func frames(_ text: String, transferId: String, clipboardId: String) -> [CrossMouseMessage]? {
        guard !text.isEmpty, !text.utf8.contains(0), text.utf8.count <= maxBytes,
              UUID(uuidString: clipboardId) != nil, !transferId.isEmpty, transferId.utf8.count <= 64 else { return nil }
        let data = Data(text.utf8)
        var frames = [CrossMouseMessage(type: "clipboard-begin", transferId: transferId,
            clipboardId: clipboardId, clipboardBytes: data.count)]
        for offset in stride(from: 0, to: data.count, by: chunkBytes) {
            frames.append(CrossMouseMessage(type: "clipboard-chunk", transferId: transferId,
                clipboardId: clipboardId, clipboardIndex: offset / chunkBytes,
                clipboardData: data.subdata(in: offset..<min(data.count, offset + chunkBytes)).base64EncodedString()
                    .replacingOccurrences(of: "+", with: "-").replacingOccurrences(of: "/", with: "_")))
        }
        frames.append(CrossMouseMessage(type: "clipboard-commit", transferId: transferId, clipboardId: clipboardId))
        return frames
    }
}

/// Read on an explicit Windows entry, never in an event tap or periodic timer.
/// A named pasteboard is injectable for tests; tests never read .general.
@MainActor
public final class MacTextClipboard {
    public struct Snapshot {
        public let changeCount: Int
        public let text: String
    }
    public enum ReadResult {
        case text(Snapshot), unchanged, unavailable, excluded, tooLarge
    }
    private var acknowledgedChange: Int?
    public init() {}

    public func read(_ board: NSPasteboard) -> ReadResult {
        let change = board.changeCount
        guard change != acknowledgedChange else { return .unchanged }
        let types = Set((board.types ?? []).map(\.rawValue))
        // Applications can mark sensitive/transient data. These markers are
        // advisory, not a guarantee that every password app supplies them.
        let excluded: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
            "org.nspasteboard.AutoGeneratedType", "org.nspasteboard.RemoteClipboardType",
            "com.agilebits.onepassword", "public.file-url", "NSFilenamesPboardType"]
        guard types.isDisjoint(with: excluded) else { return .excluded }
        guard let text = board.string(forType: .string), !text.isEmpty,
              board.changeCount == change, !text.utf8.contains(0) else { return .unavailable }
        guard text.utf8.count <= TextClipboardWire.maxBytes else { return .tooLarge }
        return .text(Snapshot(changeCount: change, text: text))
    }

    /// A network send is not a successful Windows clipboard write.
    public func acknowledge(changeCount: Int) { acknowledgedChange = changeCount }
}
